import SwiftData
import SwiftUI

/// Everything about sharing OpenAI audio through Google Drive in one place: signing in, what happens on its own
/// (looking in Drive before generating, backing up new audio, cellular), taking the whole library's audio from Drive
/// or backing it all up, and the same for one article at a time. Opened from Settings and from the library's + menu.
struct GoogleDriveSettingsView: View {
    @Query(sort: \Article.addedAt, order: .reverse) private var articles: [Article]
    @AppStorage(SettingsKeys.googleClientID) private var clientID = ""
    @AppStorage(SettingsKeys.openAIVoice) private var openAIVoice = OpenAISpeechEngine.defaultVoice
    @AppStorage(SettingsKeys.driveUploadAnyNetwork) private var uploadAnyNetwork = false
    @AppStorage(SettingsKeys.driveLookUpFirst) private var lookUpFirst = true
    @AppStorage(SettingsKeys.driveAutoBackUp) private var autoBackUp = true
    @State private var account = GoogleAccount.shared
    @State private var drive = DriveAudioStore.shared
    @State private var downloader = AudioDownloader.shared
    @State private var vocabSync = VocabSync.shared
    @State private var book = VocabularyBook.shared
    @State private var isSigningIn = false
    @State private var signInError: String?
    /// A pull or backup being worked out, so its button shows that something is happening.
    @State private var isPreparing = false
    @State private var prompt: AudioDownloadPrompt?
    /// Each article's backup, worked out when the page opens and again as uploads and downloads go.
    @State private var byArticle: [PersistentIdentifier: DriveAudioStore.ArticleBackup] = [:]

    /// An empty field means the built-in client id.
    private var hasValidClientID: Bool { clientID.isEmpty || GoogleOAuth.Client(id: clientID) != nil }

    var body: some View {
        Form {
            accountSection
            if account.isSignedIn {
                automaticSection
                librarySection
                wordBookSection
                if !articles.isEmpty { byArticleSection }
            }
            clientSection
        }
        .navigationTitle("Google Drive")
        .navigationBarTitleDisplayMode(.inline)
        .audioDownloadPrompt($prompt)
        .task(id: BreakdownInput(
            signedIn: account.isSignedIn, uploaded: drive.uploadedCount / 10, pending: drive.pendingUploads.isEmpty,
            uploading: drive.isUploading, count: articles.count, voice: openAIVoice, preparing: isPreparing,
            downloaded: downloader.donePieces / 10, downloading: downloader.isRunning
        )) {
            guard account.isSignedIn else { return }
            await drive.syncIndex()
            let (indexed, pending, manifests) = (drive.indexedKeys, Set(drive.pendingUploads), drive.manifestNames)
            var result: [PersistentIdentifier: DriveAudioStore.ArticleBackup] = [:]
            for article in articles {
                result[article.persistentModelID] = await DriveAudioStore.backup(
                    url: article.sourceURL.absoluteString, blocksData: article.blocksData, voice: openAIVoice,
                    indexed: indexed, pending: pending, manifests: manifests
                )
            }
            byArticle = result
        }
    }

    // MARK: - Account

    private var accountSection: some View {
        Section {
            switch account.state {
            case .signedIn(let email):
                LabeledContent("Signed In", value: email ?? "Google account")
                Button("Sign Out", role: .destructive) {
                    account.signOut()
                    drive.reset()
                }
            case .signedOut:
                Button {
                    signIn()
                } label: {
                    HStack {
                        Label("Sign In with Google", systemImage: "person.crop.circle.badge.checkmark")
                        if isSigningIn {
                            Spacer()
                            ProgressView()
                        }
                    }
                }
                .disabled(!hasValidClientID || isSigningIn)
            }
            if let message = signInError ?? account.problem {
                Label(message, systemImage: "exclamationmark.triangle")
                    .font(.callout)
                    .foregroundStyle(.red)
            }
        } footer: {
            Text("Audio generated by OpenAI is kept in a WikiReader Cache folder in your Google Drive, shared with your other devices and the Chrome extension, so the same text is paid for once. The app can only see files it or the extension created. When Google asks what WikiReader may access, tick the Google Drive box.")
        }
    }

    private func signIn() {
        signInError = nil
        isSigningIn = true
        Task {
            defer { isSigningIn = false }
            do {
                try await account.signIn()
                drive.reset()
                drive.pumpUploads()
                Task { await vocabSync.sync() }
                if drive.isBackingUpAutomatically {
                    let library = articles.map { (title: $0.title, url: $0.sourceURL.absoluteString, blocksData: $0.blocksData) }
                    await drive.backUp(library, voice: openAIVoice, showsProgress: true)
                }
            } catch let error as GoogleAuthError {
                if error != .cancelled { signInError = error.message }
            } catch {
                signInError = error.localizedDescription
            }
        }
    }

    // MARK: - Automatic

    private var automaticSection: some View {
        Section {
            Toggle("Check Drive First", isOn: $lookUpFirst)
            Toggle("Back Up New Audio", isOn: $autoBackUp)
            Toggle("Upload over Cellular", isOn: $uploadAnyNetwork)
                .onChange(of: uploadAnyNetwork) { drive.pumpUploads() }
        } header: {
            Text("Automatic")
        } footer: {
            Text("Check Drive First: before a paragraph is generated, it is looked for in Drive and taken from there for free. Back Up New Audio: each paragraph goes up as soon as it is generated, and whatever Drive lacks goes up when WikiReader opens; turned off, only what you back up below or from an article goes up. Uploads run while WikiReader is open, on Wi-Fi only unless Upload over Cellular is on (a long article is about 80 MB).")
        }
    }

    // MARK: - Whole library

    private var librarySection: some View {
        Section {
            if downloader.phase != .idle && downloader.isFromDriveOnly {
                AudioDownloadStatusRow()
            }
            if drive.backupRun != nil {
                DriveBackupStatusRow()
            }
            actionButton(
                "Download All from Drive", systemImage: "icloud.and.arrow.down",
                detail: pullDetail(byArticle.values), action: { pull(articles) }
            )
            .disabled(articles.isEmpty || downloader.isRunning)
            actionButton(
                "Back Up All to Drive", systemImage: "icloud.and.arrow.up",
                detail: backUpDetail(byArticle.values), action: { backUp(articles) }
            )
            .disabled(articles.isEmpty)
            LabeledContent("Waiting to Upload", value: uploadStatus)
            LabeledContent("This Session", value: "\(drive.downloadedCount) from Drive · \(drive.uploadedCount) uploaded")
            if let error = drive.lastError {
                Label(error, systemImage: "exclamationmark.triangle")
                    .font(.callout)
                    .foregroundStyle(.orange)
            }
        } header: {
            Text("Whole Library · \(openAIVoice.capitalized)")
        } footer: {
            Text("Downloading takes the \(openAIVoice.capitalized) audio that is in Drive but not on this iPhone; nothing is generated, so it's free. Backing up sends only what Drive lacks, in any voice. For some articles, tap them below, or use Select Articles in the library.")
        }
    }

    private func actionButton(_ title: String, systemImage: String, detail: String?, action: @escaping () -> Void) -> some View {
        Button(action: action) {
            HStack {
                Label {
                    VStack(alignment: .leading, spacing: 2) {
                        Text(title)
                        if let detail {
                            Text(detail)
                                .font(.caption)
                                .foregroundStyle(Color.secondary)
                        }
                    }
                } icon: {
                    Image(systemName: systemImage)
                }
                if isPreparing {
                    Spacer()
                    ProgressView()
                }
            }
        }
        .disabled(isPreparing)
    }

    private var uploadStatus: String {
        let count = drive.pendingUploads.count
        if drive.isUploading { return "\(count) · uploading…" }
        if drive.isWaitingForFreeNetwork { return "\(count) · waiting for Wi-Fi" }
        return "\(count)"
    }

    /// "12 parts not on this iPhone · about 9 min", for what downloading `backups` from Drive would bring.
    private func pullDetail(_ backups: some Collection<DriveAudioStore.ArticleBackup>) -> String? {
        guard backups.count == articles.count else { return nil }
        let pieces = backups.reduce(0) { $0 + $1.piecesOnlyOnDrive }
        guard pieces > 0 else { return "Nothing in Drive that isn't on this iPhone" }
        let characters = backups.reduce(0) { $0 + $1.charactersOnlyOnDrive }
        return "\(pieces == 1 ? "1 part" : "\(pieces) parts") not on this iPhone · about \(AudioFormat.duration(minutes: ArticleAudio.minutes(forCharacters: characters))) · free"
    }

    private func backUpDetail(_ backups: some Collection<DriveAudioStore.ArticleBackup>) -> String? {
        guard backups.count == articles.count else { return nil }
        let missing = backups.reduce(0) { $0 + $1.missing }
        let waiting = backups.reduce(0) { $0 + $1.waiting }
        if missing > 0 { return missing == 1 ? "1 part on this iPhone isn't in Drive" : "\(missing) parts on this iPhone aren't in Drive" }
        if waiting > 0 { return "\(waiting) parts waiting to upload" }
        return "Everything on this iPhone is in Drive"
    }

    private func pull(_ chosen: [Article]) {
        isPreparing = true
        Task {
            prompt = await LibraryActions.drivePullPrompt(for: chosen)
            isPreparing = false
        }
    }

    private func backUp(_ chosen: [Article]) {
        isPreparing = true
        Task {
            prompt = await LibraryActions.backUpToDrive(chosen)
            isPreparing = false
        }
    }

    // MARK: - Word book

    private var wordBookSection: some View {
        Section {
            LabeledContent("Words", value: "\(book.count)")
            LabeledContent("Sync", value: vocabSyncText)
            Button {
                Task { await vocabSync.sync() }
            } label: {
                HStack {
                    Label("Sync Word Book Now", systemImage: "arrow.triangle.2.circlepath")
                    if vocabSync.state == .syncing {
                        Spacer()
                        ProgressView()
                    }
                }
            }
            .disabled(vocabSync.state == .syncing)
        } header: {
            Text("Word Book")
        } footer: {
            Text("Saved words are one book shared with your other devices and the Chrome extension (vocab.json in the WikiReader Cache folder). It syncs when WikiReader comes to the front and a few seconds after you save or delete a word. Deleting a word deletes it everywhere.")
        }
    }

    private var vocabSyncText: String {
        switch vocabSync.state {
        case .idle: "Not yet"
        case .syncing: "Syncing…"
        case .synced: vocabSync.lastSynced.map { "Synced \($0.formatted(.relative(presentation: .named)))" } ?? "Synced"
        case .waitingForChrome: "Waiting for the Chrome extension"
        case .failed(let message): message
        }
    }

    // MARK: - By article

    private struct BreakdownInput: Equatable {
        var signedIn: Bool
        var uploaded: Int
        var pending: Bool
        var uploading: Bool
        var count: Int
        var voice: String
        var preparing: Bool
        var downloaded: Int
        var downloading: Bool
    }

    private var byArticleSection: some View {
        Section {
            summaryRow
            ForEach(articles) { article in
                let backup = byArticle[article.persistentModelID]
                Menu {
                    Section(article.title) {
                        Button("Download from Drive", systemImage: "icloud.and.arrow.down") { pull([article]) }
                            .disabled(downloader.isRunning)
                        Button("Back Up to Drive", systemImage: "icloud.and.arrow.up") { backUp([article]) }
                    }
                } label: {
                    HStack(spacing: 8) {
                        VStack(alignment: .leading, spacing: 3) {
                            Text(article.title)
                                .foregroundStyle(.primary)
                                .lineLimit(1)
                            BackupStatusLine(backup: backup)
                                .multilineTextAlignment(.leading)
                        }
                        Spacer(minLength: 0)
                        Image(systemName: "ellipsis.circle")
                            .foregroundStyle(Color.accentColor)
                    }
                    .padding(.vertical, 2)
                    .contentShape(Rectangle())
                }
                // A menu's label takes the accent color; the row reads as text, with only the icon tinted.
                .tint(.primary)
                .disabled(isPreparing)
            }
        } header: {
            Text("By Article · \(openAIVoice.capitalized)")
        } footer: {
            Text("Tap an article to download its audio from Drive or back it up. Backed up means every part of the article's audio on this iPhone, in any voice, is in Google Drive, and the article is listed there for the Chrome extension. Parts and sizes are for the \(openAIVoice.capitalized) voice.")
        }
    }

    @ViewBuilder
    private var summaryRow: some View {
        let states = articles.compactMap { byArticle[$0.persistentModelID]?.state }
        if states.count == articles.count {
            let withAudio = states.filter { $0 != .noAudio }
            let done = withAudio.filter { $0 == .backedUp }.count
            if withAudio.isEmpty {
                Label("No downloaded audio to back up", systemImage: "icloud")
                    .foregroundStyle(.secondary)
            } else if done == withAudio.count {
                Label(done == 1 ? "1 article backed up" : "All \(done) articles with audio are backed up", systemImage: "checkmark.icloud.fill")
                    .foregroundStyle(.green)
            } else {
                Label("\(done) of \(withAudio.count) articles backed up", systemImage: "icloud.and.arrow.up")
                    .foregroundStyle(.orange)
            }
        }
    }

    // MARK: - Client id

    private var clientSection: some View {
        Section {
            TextField(GoogleAccount.defaultClientID, text: $clientID)
                .textInputAutocapitalization(.never)
                .autocorrectionDisabled()
                .font(.callout.monospaced())
                .disabled(account.isSignedIn)
            if !clientID.isEmpty && !hasValidClientID {
                Text("That doesn't look like a client ID; it ends in .apps.googleusercontent.com.")
                    .font(.footnote)
                    .foregroundStyle(.red)
            }
        } header: {
            Text("iOS Client ID (Advanced)")
        } footer: {
            Text("Leave empty to use the built-in one, the iOS OAuth client of the WikiReader Google Cloud project (the same project as the Chrome extension's). It identifies the app and isn't a secret. Sign out to change it.")
        }
    }
}

/// The Google Drive page on its own, from the library's + menu.
struct GoogleDriveSheet: View {
    @Environment(\.dismiss) private var dismiss

    var body: some View {
        NavigationStack {
            GoogleDriveSettingsView()
                .toolbar {
                    ToolbarItem(placement: .confirmationAction) {
                        Button("Done") { dismiss() }
                    }
                }
        }
    }
}
