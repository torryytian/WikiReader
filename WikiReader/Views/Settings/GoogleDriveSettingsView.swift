import SwiftData
import SwiftUI

/// Sharing OpenAI audio through Google Drive: the Google Cloud client id, signing in and out, what is waiting to be
/// uploaded, and moving the audio already on this iPhone.
struct GoogleDriveSettingsView: View {
    @Query(sort: \Article.addedAt, order: .reverse) private var articles: [Article]
    @AppStorage(SettingsKeys.googleClientID) private var clientID = ""
    @AppStorage(SettingsKeys.openAIVoice) private var openAIVoice = OpenAISpeechEngine.defaultVoice
    @State private var account = GoogleAccount.shared
    @State private var drive = DriveAudioStore.shared
    @State private var isSigningIn = false
    @State private var signInError: String?
    @State private var isQueueing = false
    @State private var queuedMessage: String?

    private var hasValidClientID: Bool { GoogleOAuth.Client(id: clientID) != nil }

    var body: some View {
        Form {
            accountSection
            if account.isSignedIn { statusSection }
            clientSection
        }
        .navigationTitle("Google Drive")
        .navigationBarTitleDisplayMode(.inline)
    }

    // MARK: - Account

    private var accountSection: some View {
        Section {
            switch account.state {
            case .signedIn(let email):
                LabeledContent("Signed In", value: email ?? "Google account")
                Button("Sign Out", role: .destructive) {
                    account.signOut()
                    drive.reset()
                }
            case .signedOut:
                Button {
                    signIn()
                } label: {
                    HStack {
                        Label("Sign In with Google", systemImage: "person.crop.circle.badge.checkmark")
                        if isSigningIn {
                            Spacer()
                            ProgressView()
                        }
                    }
                }
                .disabled(!hasValidClientID || isSigningIn)
            }
            if let message = signInError ?? account.problem {
                Label(message, systemImage: "exclamationmark.triangle")
                    .font(.callout)
                    .foregroundStyle(.red)
            }
        } footer: {
            Text("Audio generated by OpenAI is kept in a WikiReader Cache folder in your Google Drive, shared with your other devices and the Chrome extension. Before a paragraph is generated, Drive is checked first, so the same text is paid for once. The app can only see files it or the extension created.")
        }
    }

    private func signIn() {
        signInError = nil
        isSigningIn = true
        Task {
            defer { isSigningIn = false }
            do {
                try await account.signIn()
                drive.reset()
                drive.pumpUploads()
            } catch let error as GoogleAuthError {
                if error != .cancelled { signInError = error.message }
            } catch {
                signInError = error.localizedDescription
            }
        }
    }

    // MARK: - Status

    private var statusSection: some View {
        Section {
            LabeledContent("Waiting to Upload", value: drive.isUploading ? "\(drive.pendingUploads.count) · uploading…" : "\(drive.pendingUploads.count)")
            LabeledContent("This Session", value: "\(drive.downloadedCount) from Drive · \(drive.uploadedCount) uploaded")
            if let error = drive.lastError {
                Label(error, systemImage: "exclamationmark.triangle")
                    .font(.callout)
                    .foregroundStyle(.orange)
            }
            Button {
                uploadSavedAudio()
            } label: {
                HStack {
                    Label("Upload Saved Audio", systemImage: "icloud.and.arrow.up")
                    if isQueueing {
                        Spacer()
                        ProgressView()
                    }
                }
            }
            .disabled(isQueueing || articles.isEmpty)
            if let queuedMessage {
                Text(queuedMessage)
                    .font(.footnote)
                    .foregroundStyle(.secondary)
            }
        } header: {
            Text("Status")
        } footer: {
            Text("Upload Saved Audio sends the audio already on this iPhone for your saved articles (any voice) that isn't in Drive yet, and lists the articles there. Uploads continue in the background while WikiReader is open.")
        }
    }

    private func uploadSavedAudio() {
        isQueueing = true
        queuedMessage = nil
        let library = articles.map { (title: $0.title, url: $0.sourceURL.absoluteString, blocksData: $0.blocksData) }
        Task {
            let count = await drive.uploadLibrary(library, voice: openAIVoice)
            isQueueing = false
            queuedMessage = count == 0 ? "Everything is already in Drive." : "\(count) pieces queued for upload."
        }
    }

    // MARK: - Client id

    private var clientSection: some View {
        Section {
            TextField("123456-abc.apps.googleusercontent.com", text: $clientID)
                .textInputAutocapitalization(.never)
                .autocorrectionDisabled()
                .font(.callout.monospaced())
                .disabled(account.isSignedIn)
            if !clientID.isEmpty && !hasValidClientID {
                Text("That doesn't look like a client ID; it ends in .apps.googleusercontent.com.")
                    .font(.footnote)
                    .foregroundStyle(.red)
            }
        } header: {
            Text("iOS Client ID")
        } footer: {
            Text("From Google Cloud Console → APIs & Services → Credentials, the iOS OAuth client in the same project as the Chrome extension. It identifies the app and isn't a secret. Sign out to change it.")
        }
    }
}
